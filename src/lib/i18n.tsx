const catalogs: Record<Locale, Record<MessageKey, string>> = { vi, en };

export function resolveLocale(stored: string | null): Locale {
  return stored === "en" ? "en" : "vi";
}

function initialLocale(): Locale {
  if (typeof window === "undefined") return "vi";
  return resolveLocale(window.localStorage.getItem(STORAGE_KEY));
}

export function getCurrentLocale(): Locale {
  return initialLocale();
}

function format(message: string, values?: Record<string, string | number>): string {
  if (!values) return message;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    message,
  );
}

export type Translator = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

interface I18nValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: Translator;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, updateLocale] = useState<Locale>(initialLocale);
  useEffect(() => {
    document.documentElement.lang = locale;
  }, [locale]);
  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale(next) {
      window.localStorage.setItem(STORAGE_KEY, next);
      document.documentElement.lang = next;
      updateLocale(next);
    },
    t(key, values) {
      return format(catalogs[locale][key] ?? vi[key], values);
    },
  }), [locale]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

